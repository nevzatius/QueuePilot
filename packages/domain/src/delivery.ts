import type { TriageResult } from '@queuepilot/contracts';
import { LEASE_GRACE_MS, LEASE_MS, RETRY_WATCHDOG_MS } from './policy.js';
import {
  failedEvent,
  failedState,
  isAttemptBudgetExhausted,
  isLeaseValid,
  isTerminal,
  makeEvent,
  stateWrite,
} from './state.js';
import type { DomainEvent, Lease, RequestState, StateWrite } from './state.js';
import type { EpochMs } from './time.js';

/**
 * Worker decisions (ARCHITECTURE §6). The adapter calls each function inside a Firestore transaction
 * with the freshly read state, commits `write` when it is not null, and answers Cloud Tasks with `http`.
 *
 * Delivery is at-least-once and a task is only a wake-up call (ADR-017): any task of a runnable request may
 * process it, whatever its `seq`. Duplicate, late or recreated tasks are absorbed by the lease (409), the
 * attempt budget (I5) and terminal absorption (I3), never by task identity.
 */

// ---------------------------------------------------------------------------
// decideDelivery
// ---------------------------------------------------------------------------

export interface Delivery {
  /** `seq` from the task payload. */
  readonly seq: number;
  /**
   * A fresh random lease ID generated by the adapter. It is used only when the decision acquires the
   * lease, which keeps this function deterministic.
   */
  readonly leaseId: string;
}

export type DeliveryDecision =
  /** No request document (e.g. deleted by TTL). Nothing to do. */
  | { readonly kind: 'ORPHAN'; readonly http: 200; readonly write: null }
  /** Terminal request: absorbing (I3). Only `duplicateDeliveries` is incremented. */
  | { readonly kind: 'DUPLICATE_SUPPRESSED'; readonly http: 200; readonly write: StateWrite }
  /**
   * Anomaly: `seq` is ahead of `dispatch.seq`. Tasks are created only after their `seq` commits, so this
   * indicates a bug or foreign task. No processing; the adapter logs it at ERROR.
   */
  | { readonly kind: 'FUTURE_DISPATCH'; readonly http: 200; readonly write: null }
  /** Another worker holds a valid lease. No write; Cloud Tasks retries with backoff. */
  | { readonly kind: 'LEASE_HELD'; readonly http: 409; readonly write: null }
  /** S8: the attempt budget is spent. */
  | { readonly kind: 'FAIL'; readonly http: 200; readonly reason: 'ATTEMPTS_EXHAUSTED'; readonly write: StateWrite }
  /** S2 / S3: lease acquired; the worker runs triage, then calls `decideCompletion` with `lease.id`. */
  | {
      readonly kind: 'ACQUIRE_LEASE';
      readonly http: null;
      readonly lease: Lease;
      readonly attempt: number;
      readonly takeover: boolean;
      readonly write: StateWrite;
    };

/** `decideDelivery(doc, delivery, now)`: first matching row wins. */
export function decideDelivery(state: RequestState | null, delivery: Delivery, now: EpochMs): DeliveryDecision {
  if (state === null) return { kind: 'ORPHAN', http: 200, write: null };

  if (isTerminal(state)) {
    const next: RequestState = {
      ...state,
      processing: { ...state.processing, duplicateDeliveries: state.processing.duplicateDeliveries + 1 },
      // Heals a leftover watchdog in the same write (normally already absent).
      watchdogAt: null,
    };
    return { kind: 'DUPLICATE_SUPPRESSED', http: 200, write: stateWrite('S11', state, next) };
  }

  // An older order's task is as good as the latest one: no STALE_DISPATCH (ADR-017).
  if (delivery.seq > state.dispatch.seq) return { kind: 'FUTURE_DISPATCH', http: 200, write: null };

  if (isLeaseValid(state, now)) return { kind: 'LEASE_HELD', http: 409, write: null };

  if (isAttemptBudgetExhausted(state)) {
    const next = failedState(state, 'ATTEMPTS_EXHAUSTED', now);
    const write = stateWrite('S8', state, next, [failedEvent(state, 'ATTEMPTS_EXHAUSTED', 'worker', now)]);
    return { kind: 'FAIL', http: 200, reason: 'ATTEMPTS_EXHAUSTED', write };
  }

  // S2 from ACCEPTED, S3 from PROCESSING whose lease expired (or is missing).
  const takeover = state.status === 'PROCESSING';
  const attempt = state.processing.attempts + 1;
  const lease: Lease = { id: delivery.leaseId, expiresAt: now + LEASE_MS };
  const next: RequestState = {
    ...state,
    status: 'PROCESSING',
    processing: { ...state.processing, attempts: attempt, lease },
    dispatch: {
      ...state.dispatch,
      deliveredSeq: Math.max(state.dispatch.deliveredSeq, delivery.seq),
      checks: 0,
      attentionSince: null,
    },
    watchdogAt: lease.expiresAt + LEASE_GRACE_MS,
    startedAt: state.startedAt ?? now,
  };
  const events: DomainEvent[] = [makeEvent('PROCESSING_STARTED', 'worker', next, now)];
  if (takeover) {
    const previous = state.processing.lease;
    events.push(
      makeEvent('LEASE_TAKEOVER', 'worker', next, now, {
        details: { previousLeaseExpiresAt: previous === null ? null : previous.expiresAt },
      }),
    );
  }
  return {
    kind: 'ACQUIRE_LEASE',
    http: null,
    lease,
    attempt,
    takeover,
    write: stateWrite(takeover ? 'S3' : 'S2', state, next, events),
  };
}

// ---------------------------------------------------------------------------
// decideCompletion
// ---------------------------------------------------------------------------

export interface ProcessingError {
  readonly code: string;
  readonly message: string;
}

export type ProcessingOutcome =
  | { readonly kind: 'SUCCESS'; readonly result: TriageResult }
  /** Retryable: the request returns to ACCEPTED while budget remains. */
  | { readonly kind: 'TRANSIENT_ERROR'; readonly error: ProcessingError }
  /** Not retryable (e.g. invalid content or unknown rules version). */
  | { readonly kind: 'PERMANENT_ERROR'; readonly error: ProcessingError };

export type FenceReason = 'NO_DOCUMENT' | 'TERMINAL' | 'NOT_PROCESSING' | 'LEASE_MISMATCH';

export type CompletionDecision =
  /** S4. The adapter writes `result` together with `write`. */
  | { readonly kind: 'COMPLETE'; readonly http: 200; readonly result: TriageResult; readonly write: StateWrite }
  /** S5. 503 makes Cloud Tasks redeliver the same task. */
  | { readonly kind: 'RETRY'; readonly http: 503; readonly write: StateWrite }
  /** S6 / S7. */
  | {
      readonly kind: 'FAIL';
      readonly http: 200;
      readonly reason: 'ATTEMPTS_EXHAUSTED' | 'PERMANENT_ERROR';
      readonly write: StateWrite;
    }
  /**
   * The caller no longer holds the current lease (I4). Nothing is written. A terminal request answers
   * 200 because nothing is left to do; otherwise 409 keeps the task alive for whoever owns the request now.
   */
  | { readonly kind: 'FENCED'; readonly http: 200 | 409; readonly reason: FenceReason; readonly write: null };

/**
 * Commits the result of one triage run. Only the holder of the current `leaseId` may move a request out
 * of PROCESSING (I4). A matching lease that has expired but was not taken over still commits: no other
 * holder exists, and a takeover would have replaced the lease ID.
 */
export function decideCompletion(
  state: RequestState | null,
  leaseId: string,
  outcome: ProcessingOutcome,
  now: EpochMs,
): CompletionDecision {
  if (state === null) return { kind: 'FENCED', http: 200, reason: 'NO_DOCUMENT', write: null };
  if (isTerminal(state)) return { kind: 'FENCED', http: 200, reason: 'TERMINAL', write: null };
  if (state.status !== 'PROCESSING') return { kind: 'FENCED', http: 409, reason: 'NOT_PROCESSING', write: null };
  if (state.processing.lease?.id !== leaseId) {
    return { kind: 'FENCED', http: 409, reason: 'LEASE_MISMATCH', write: null };
  }

  switch (outcome.kind) {
    case 'SUCCESS': {
      const next: RequestState = {
        ...state,
        status: 'COMPLETED',
        processing: { ...state.processing, lease: null },
        dispatch: { ...state.dispatch, attentionSince: null },
        watchdogAt: null,
        completedAt: now,
      };
      const write = stateWrite('S4', state, next, [makeEvent('COMPLETED', 'worker', state, now)]);
      return { kind: 'COMPLETE', http: 200, result: outcome.result, write };
    }
    case 'TRANSIENT_ERROR': {
      if (isAttemptBudgetExhausted(state)) {
        const next = withLastError(failedState(state, 'ATTEMPTS_EXHAUSTED', now), outcome.error, now);
        const write = stateWrite('S6', state, next, [failedEvent(state, 'ATTEMPTS_EXHAUSTED', 'worker', now)]);
        return { kind: 'FAIL', http: 200, reason: 'ATTEMPTS_EXHAUSTED', write };
      }
      const next: RequestState = withLastError(
        {
          ...state,
          status: 'ACCEPTED',
          processing: { ...state.processing, lease: null },
          dispatch: { ...state.dispatch, attentionSince: null },
          watchdogAt: now + RETRY_WATCHDOG_MS,
        },
        outcome.error,
        now,
      );
      const event = makeEvent('RETRY_SCHEDULED', 'worker', state, now, { details: { code: outcome.error.code } });
      return { kind: 'RETRY', http: 503, write: stateWrite('S5', state, next, [event]) };
    }
    case 'PERMANENT_ERROR': {
      const next = withLastError(failedState(state, 'PERMANENT_ERROR', now), outcome.error, now);
      const write = stateWrite('S7', state, next, [failedEvent(state, 'PERMANENT_ERROR', 'worker', now)]);
      return { kind: 'FAIL', http: 200, reason: 'PERMANENT_ERROR', write };
    }
  }
}

function withLastError(state: RequestState, error: ProcessingError, now: EpochMs): RequestState {
  return { ...state, processing: { ...state.processing, lastError: { code: error.code, message: error.message, at: now } } };
}
